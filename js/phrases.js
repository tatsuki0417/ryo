// ===================================================================
// phrases.js  ―  ペットの「今日のひとこと」
// -------------------------------------------------------------------
// バズの燃料になる部分。ペットが毎日ちがう一言をつぶやき、
// それをシェアカードにして拡散してもらう狙いです。
// ★将来ここをAIに差し替えると「トモコレ」的な無限セリフになります。
//   （まずはコストゼロの固定リストで動かします）
// ===================================================================

const NORMAL = [
  'きょうもいっしょにいてくれてありがとう',
  'なんかいいことあった？きかせて',
  'ひまだな〜。かまってほしいな',
  'きみのこと、けっこうすきかも',
  'そとはどんなてんきかな？',
  'ぼーっとするのもわるくないね',
  'おなかすいてないよ、げんきげんき！',
  'きょうのきぶんは…まあまあ！',
];

const HUNGRY = [
  'おなか…ぺこぺこだよ…',
  'ごはんのおとがきこえた…きがする',
  'なにかたべたいな…おねがい',
];

const DIRTY = [
  'ちょっとおそうじしてほしいな…',
  'まわりがちょっとよごれてきたかも',
];

const HAPPY = [
  'さいこうのきぶん！ありがとう！',
  'えへへ、うれしくてぴょんぴょんしちゃう',
  'きみといるとたのしいな！',
];

const SLEEP = [
  'すぴー…すぴー…',
  'いいゆめみてるよ…zzz',
];

const DEAD = [
  'たくさんのおもいで、ありがとう',
  'またあたらしい子とであえるよ',
];

// ペットの状態に合わせて、ふさわしい一言をひとつ選ぶ
export function pickPhrase(pet) {
  let pool;
  if (pet.isDead) pool = DEAD;
  else if (pet.isSleeping) pool = SLEEP;
  else if (pet.hunger <= 1) pool = HUNGRY;
  else if (pet.poop >= 3) pool = DIRTY;
  else if (pet.mood >= 4 && pet.hunger >= 4) pool = HAPPY;
  else pool = NORMAL;

  // 「その日」で固定したいので、日付＋名前から擬似ランダムに選ぶ
  // （同じ日なら何度開いても同じ一言＝日替わり感が出る）
  const daySeed = Math.floor(Date.now() / (1000 * 60 * 60 * 24));
  const idx = (daySeed + pet.name.length) % pool.length;
  return pool[idx];
}
