// -------------------------------------------------------------------
// スプライト（文字の配列）を canvas に描く関数
//   ctx     : canvasの描画コンテキスト
//   sprite  : SPRITES の中の1つ
//   offsetY : 上下のズレ（ぴょこぴょこ動かすのに使う）
//   color   : ドットの色
// -------------------------------------------------------------------
export function drawSprite(ctx, sprite, offsetY = 0, color = '#2b3a1a') {
  ctx.fillStyle = color;
  for (let row = 0; row < sprite.length; row++) {
    for (let col = 0; col < sprite[row].length; col++) {
      if (sprite[row][col] === 'x') {
        // 角を少し丸めるとLCDっぽい柔らかさが出る
        const x = col * DOT;
        const y = row * DOT + offsetY;
        ctx.fillRect(x + 0.5, y + 0.5, DOT - 1, DOT - 1);
      }
    }
  }
}
